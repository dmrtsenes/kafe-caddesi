  check('pickup-unlock-moving',()=>pickup.update(.25));
  check('pickup-unlock-settled',()=>pickup.update(1));
  check('pickup-hidden',()=>pickup.setLocked(false,true));
  check('pickup-shown',()=>{pickup.setLocked(false);pickup.update(0);});
